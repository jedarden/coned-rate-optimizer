/* Generate and verify the release-bound bill-reconstruction test manifest.

   The published bill-history fixture is the ground truth; this script never
   derives expected bills from calc.js. It records the source fixture's
   expected lines and a fingerprint of the complete rates.json release so a
   tariff edit cannot quietly leave the reconstruction tests tied to an older
   release.

   Usage:
     node scripts/regenerate-reconstruction-tests.js
     node scripts/regenerate-reconstruction-tests.js --check

   Exit codes: 0 = generated/current, 1 = stale, malformed, or unreadable. */
"use strict";

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MANIFEST_PATH = path.join(ROOT, "test", "fixtures", "bill-reconstruction-tests.json");

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

// Object-key ordering is not part of JSON's data model. Canonicalization keeps
// the release fingerprint stable when a formatter changes whitespace or key
// order, while still changing for every data/metadata change in rates.json.
function canonical(value) {
  if (Array.isArray(value)) return "[" + value.map(canonical).join(",") + "]";
  if (value && typeof value === "object") {
    return "{" + Object.keys(value).sort().map((key) =>
      JSON.stringify(key) + ":" + canonical(value[key])).join(",") + "}";
  }
  return JSON.stringify(value);
}

function fingerprint(value) {
  return crypto.createHash("sha256").update(canonical(value)).digest("hex");
}

function buildManifest(root = ROOT) {
  const ratesPath = path.join(root, "public", "rates.json");
  const sourcePath = path.join(root, "test", "fixtures", "bill-history-sc1-nyc.json");
  const rates = readJson(ratesPath);
  const source = readJson(sourcePath);
  const years = Object.keys(source.years || {}).sort((a, b) => Number(a) - Number(b));

  if (!rates.meta || typeof rates.meta.version !== "string") {
    throw new Error("public/rates.json is missing meta.version");
  }
  if (!source.sampleKwh || !source.years || !years.length) {
    throw new Error("bill-history-sc1-nyc.json must contain sampleKwh and at least one year");
  }

  return {
    _comment: "Generated by scripts/regenerate-reconstruction-tests.js from the published bill-history fixture; do not hand edit.",
    schemaVersion: 1,
    generatedBy: "scripts/regenerate-reconstruction-tests.js",
    release: {
      version: rates.meta.version,
      fingerprint: fingerprint(rates),
    },
    source: {
      path: "test/fixtures/bill-history-sc1-nyc.json",
      fingerprint: fingerprint(source),
      publication: source.publication,
      retrievedFrom: source.retrievedFrom,
      transcribed: source.transcribed,
    },
    sampleKwh: source.sampleKwh,
    cases: years.map((year) => ({
      year: Number(year),
      expected: source.years[year].bill,
    })),
  };
}

function serialized(value) {
  return JSON.stringify(value, null, 2) + "\n";
}

function check(root = ROOT) {
  const expected = buildManifest(root);
  const manifestPath = path.join(root, "test", "fixtures", "bill-reconstruction-tests.json");
  let actual;
  try {
    actual = readJson(manifestPath);
  } catch (error) {
    console.error("reconstruction-tests: cannot read " + path.relative(root, manifestPath) + ": " + error.message);
    return false;
  }
  if (canonical(actual) !== canonical(expected)) {
    console.error("reconstruction-tests: " + path.relative(root, manifestPath) + " is stale");
    console.error("Regenerate it with: node scripts/regenerate-reconstruction-tests.js");
    return false;
  }
  console.log("reconstruction-tests: OK — " + expected.cases.length +
    " published periods bound to rates v" + expected.release.version);
  return true;
}

function main() {
  try {
    if (process.argv.includes("--check")) {
      if (!check()) process.exitCode = 1;
      return;
    }
    const output = serialized(buildManifest());
    fs.writeFileSync(MANIFEST_PATH, output);
    console.log("reconstruction-tests: regenerated " + path.relative(ROOT, MANIFEST_PATH));
  } catch (error) {
    console.error("reconstruction-tests: " + error.message);
    process.exitCode = 1;
  }
}

if (require.main === module) main();

module.exports = { buildManifest, canonical, fingerprint, check };
